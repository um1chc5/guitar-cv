let lang = 'en';
try {
  lang = localStorage.getItem(KEY) || (navigator.language?.toLowerCase().startsWith('vi') ? 'vi' : 'en');
} catch { /* ignore */ }
if (!DICT[lang]) lang = 'en';

export const getLang = () => lang;

export function setLang(next) {
  lang = DICT[next] ? next : 'en';
  try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// A { en, vi } field (or a plain string) in the current language.
export const L = (v) => (v && typeof v === 'object' && !Array.isArray(v) ? v[lang] ?? v.en : v);

// Pattern names are data values (English); show them translated where a translation exists.
export const patternLabel = (name) => DICT[lang][`pat.${name}`] ?? name;
export const sequenceLabel = (name) => t(`seq.${name}`);

export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
